package main

import "fmt"

func main() {
	segasaturn := true
	if segasaturn {
		fmt.Println("セガサターン城！")
	}
}

/* The exercise above exemplifies how a simple conditional 
structure in Go works. This exercise checks if the variable `segasaturn` 
is true and if it is, it prints the message "セガサターン城！(Play Sega Saturn)" to the console. */
